"""Generate the reference pages in ``docs/`` from the code, so they cannot go stale.

    python -m slopguard.docgen          # rewrite docs/rules.md and docs/cli.md
    python -m slopguard.docgen --check  # exit 1 if either is out of date (used by tests)
"""

from __future__ import annotations

import sys
from pathlib import Path

import typer.main

from slopguard.cli import app, rules_markdown


def _is_argument(param: object) -> bool:
    # Typer versions differ in whether they depend on click or vendor it, so no isinstance here.
    return type(param).__name__.endswith("Argument")


def _default(param: object) -> str:
    default = getattr(param, "default", None)
    if getattr(param, "is_flag", False):
        return "on" if default else "off"
    if default in (None, (), [], ""):
        return ""
    return f"`{default}`"


def _usage(name: str, params: list) -> str:
    parts = [f"slopguard {name}", "[OPTIONS]"]
    for param in params:
        if _is_argument(param):
            token = param.name.upper()
            many = getattr(param, "nargs", 1) == -1
            token = f"{token}..." if many else token
            parts.append(token if param.required else f"[{token}]")
    return " ".join(parts)


def cli_markdown() -> str:
    root = typer.main.get_command(app)
    lines = [
        "# Command reference",
        "",
        "Generated by `python -m slopguard.docgen`. Do not edit by hand.",
        "",
        "Exit codes for `scan`, `regress`, `fix` and `bench`: `0` nothing at or above the threshold, "
        "`1` findings at or above it, `2` usage or configuration error, `3` internal error.",
        "",
        "| Command | What it does |",
        "| --- | --- |",
    ]
    for name, command in root.commands.items():
        summary = (command.help or "").strip().splitlines()[0]
        lines.append(f"| [`slopguard {name}`](#slopguard-{name}) | {summary} |")
    for name, command in root.commands.items():
        lines += ["", f"## slopguard {name}", "", (command.help or "").strip(), "",
                  "```text", _usage(name, command.params), "```"]
        options = [p for p in command.params if not _is_argument(p)]
        if options:
            lines += ["", "| Option | Description | Default |", "| --- | --- | --- |"]
            for option in options:
                flags = ", ".join(f"`{o}`" for o in option.opts)
                lines.append(f"| {flags} | {(option.help or '').replace('|', '/')} | {_default(option)} |")
    return "\n".join(lines) + "\n"


def targets(root: Path) -> dict[Path, str]:
    return {root / "docs" / "rules.md": rules_markdown(), root / "docs" / "cli.md": cli_markdown()}


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    root = Path(__file__).resolve().parents[2]
    stale = [path for path, text in targets(root).items() if not path.exists() or path.read_text() != text]
    if "--check" in args:
        for path in stale:
            print(f"out of date: {path.relative_to(root)} (run: python -m slopguard.docgen)")
        return 1 if stale else 0
    for path, text in targets(root).items():
        path.write_text(text)
        print(f"wrote {path.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
